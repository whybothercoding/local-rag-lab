#!/usr/bin/env python3
"""Regenerate eval/corpus/stress/: 12 near-identical regional policy files, 6 limits each (72 chunks).

The ordinary corpus has 3-6 files per workspace, so every chunk always fits the candidate pool and
RETRIEVAL_*_K cannot matter. Here a question about one region and one limit competes with 11 other
regions' chunk on the same limit and 5 other limits of the same region, differing in a name and a figure.
Every figure is unique (100-171), so a keyword hit means the exact chunk reached the answer.
Run `python eval/build_stress_corpus.py` after editing, then `make eval`. The golden cases in
golden.json (suite `stress`) are generated by the same table: `python eval/build_stress_corpus.py --cases`.
"""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / "corpus" / "stress"
REGIONS = ["Alder", "Birch", "Cedar", "Dogwood", "Elm", "Fir", "Ginkgo", "Hazel", "Ironwood", "Juniper", "Larch", "Maple"]
# (heading, sentence template, question template)
LIMITS = [
    ("Hotel cap", "The hotel cap is {n} EUR per night.", "What is the hotel cap per night at the {r} office?"),
    ("Meal allowance", "The meal allowance is {n} EUR per day.", "How much is the daily meal allowance at the {r} office?"),
    ("Mileage cap", "Mileage claims are capped at {n} km per month.", "What is the monthly mileage cap at the {r} office?"),
    ("Training budget", "The training budget is {n} EUR per year.", "What is the yearly training budget at the {r} office?"),
    ("Parking cap", "The parking subsidy is capped at {n} EUR per month.", "What is the monthly parking subsidy cap at the {r} office?"),
    ("Taxi limit", "A single taxi ride may cost at most {n} EUR.", "What is the maximum cost of a single taxi ride at the {r} office?"),
]


def figure(region: int, limit: int) -> int:
    return 100 + region * len(LIMITS) + limit


def write_files() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for r, region in enumerate(REGIONS):
        lines = [f"# {region} office policy", ""]
        for k, (heading, sentence, _) in enumerate(LIMITS):
            lines += [f"## {heading}", sentence.format(n=figure(r, k)), ""]
        (OUT / f"{region.lower()}.md").write_text("\n".join(lines), encoding="utf-8")


# Cases: a spread of regions and limits; every third is calibration.
PICKS = [(0, 0), (1, 2), (2, 4), (3, 1), (4, 5), (5, 3), (6, 0), (7, 4), (8, 2), (9, 5), (10, 1), (11, 3), (3, 4), (6, 5), (9, 0), (11, 1)]


def cases() -> list[dict]:
    out = []
    for i, (r, k) in enumerate(PICKS):
        out.append({
            "id": f"stress-{REGIONS[r].lower()}-{LIMITS[k][0].lower().replace(' ', '-')}",
            "split": "calibration" if i % 4 == 3 else "test",
            "workspace": "stress",
            "question": LIMITS[k][2].format(r=REGIONS[r]),
            "expected_sources": [f"{REGIONS[r].lower()}.md"],
            "expected_keywords": [str(figure(r, k))],
            "suite": "stress",
            "lang": "en",
        })
    return out


if __name__ == "__main__":
    if "--cases" in sys.argv:
        print(json.dumps(cases(), indent=1, ensure_ascii=False))
    else:
        write_files()
        print(f"wrote {len(REGIONS)} files to {OUT}")
